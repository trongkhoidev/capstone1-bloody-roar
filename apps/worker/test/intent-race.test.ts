import { afterAll, beforeAll, expect, test } from "bun:test";
import { randomBytes } from "node:crypto";
import { prisma } from "@bloody-roar/database";
import { assertTestDatabase } from "@bloody-roar/database/test-guard";
import { encodeAbiParameters, encodeEventTopics } from "@bloody-roar/shared";
import { ESCROW_ABI, type Hex } from "@bloody-roar/shared/escrow";
import { reconcileIndexedIntents } from "../src/reconciler/intents";
import { handleReorg } from "../src/indexer/reorg";
import { cleanupChain, fakeRpc, newChain, rawLog, scanToHead, testConfig } from "./helpers";

const config = testConfig();
const hex = (n: number) => `0x${randomBytes(n).toString("hex")}` as Hex;
const hash = hex(32), blockHash = hex(32), txHash = hex(32), address = hex(20);
let userId = "", intentId = "", secondIntentId = "";
beforeAll(async () => {
  assertTestDatabase(process.env.TEST_DATABASE_URL);
  userId = (await prisma.user.create({ data: { walletAddress: address, role: "DEVELOPER" } })).id;
  await prisma.claimableBalance.create({ data: { chainId: config.chainId, contractAddress: config.escrowAddress, address, amountRaw: "10" } });
  intentId = (await prisma.transactionIntent.create({ data: { userId, chainId: config.chainId, contractAddress: config.escrowAddress, method: "claim", args: { recipient: address }, expiresAt: new Date(Date.now() + 60_000) } })).id;
});
afterAll(async () => {
  await prisma.notification.deleteMany({ where: { userId } });
  await prisma.transactionIntent.deleteMany({ where: { id: { in: [intentId, secondIntentId] } } });
  await prisma.claimableBalance.deleteMany({ where: { chainId: config.chainId, contractAddress: config.escrowAddress } });
  await cleanupChain(prisma, config);
  await prisma.user.deleteMany({ where: { id: userId } });
  await prisma.$disconnect();
});
test("late transaction hash confirms only its canonical claim and reorg restores submission", async () => {
  const chain = newChain();
  chain.safe = 100n;
  chain.blockHash.set(99n, hash);
  chain.blockHash.set(100n, blockHash);
  const log = rawLog({ address: config.escrowAddress, block: 100, blockHash, tx: txHash });
  log.topics = [...encodeEventTopics({ abi: ESCROW_ABI, eventName: "Claimed", args: { recipient: address, caller: address } })];
  log.data = encodeAbiParameters([{ type: "uint256" }], [10n]);
  chain.logs = [log];
  const deps = { db: prisma, rpc: fakeRpc(chain), config };
  await scanToHead(deps);
  const row = () => prisma.transactionIntent.findUniqueOrThrow({ where: { id: intentId } });
  expect((await row()).status).toBe("AWAITING_SIGNATURE");
  await prisma.transactionIntent.update({ where: { id: intentId }, data: { status: "SUBMITTED", txHash, submittedAt: new Date() } });
  const event = await prisma.chainEvent.findFirstOrThrow({ where: { txHash } });
  const secondTxHash = hex(32);
  const mixedAddress = config.escrowAddress.toUpperCase().replace("0X", "0x");
  await prisma.chainEvent.update({ where: { id: event.id }, data: { contractAddress: mixedAddress } });
  await prisma.chainEvent.create({ data: { chainId: event.chainId, contractAddress: mixedAddress, txHash: secondTxHash, logIndex: event.logIndex, txIndex: event.txIndex, blockNumber: event.blockNumber, blockHash: event.blockHash, eventName: event.eventName, args: event.args!, decoderVersion: event.decoderVersion, canonical: true } });
  secondIntentId = (await prisma.transactionIntent.create({ data: { userId, chainId: config.chainId, contractAddress: config.escrowAddress, method: "claim", args: { recipient: address }, expiresAt: new Date(Date.now() + 60_000), status: "SUBMITTED", txHash: secondTxHash, submittedAt: new Date() } })).id;
  await reconcileIndexedIntents(prisma, config);
  expect((await row()).status).toBe("CONFIRMED");
  expect((await prisma.transactionIntent.findUniqueOrThrow({ where: { id: secondIntentId } })).status).toBe("CONFIRMED");
  await prisma.transactionIntent.delete({ where: { id: secondIntentId } });
  await prisma.chainEvent.deleteMany({ where: { txHash: secondTxHash } });
  await prisma.chainEvent.update({ where: { id: event.id }, data: { contractAddress: config.escrowAddress } });
  chain.blockHash.set(100n, hex(32));
  await handleReorg(deps);
  expect((await row()).status).toBe("SUBMITTED");
  await reconcileIndexedIntents(prisma, config);
  expect((await row()).status).toBe("SUBMITTED");
});
