import { beforeAll, expect, test } from "bun:test";
import { assertTestDatabase } from "@bloody-roar/database/test-guard";
import { decodeFunctionResult, encodeFunctionData } from "@bloody-roar/shared";
import { ESCROW_ABI, type Hex } from "@bloody-roar/shared/escrow";
import { fixture } from "./harness/fixture";
import { fund, sendPrepared } from "./harness/funding";
import { gqlAs } from "./harness/gql";
import { rpc } from "./harness/chain";
import { waitFor } from "./harness/waitFor";
import { releaseFunds, submitWork } from "./harness/work";
const abi = [{ type: "function", name: "balanceOf", stateMutability: "view", inputs: [{ name: "account", type: "address" }], outputs: [{ type: "uint256" }] }] as const;
beforeAll(() => assertTestDatabase(process.env.TEST_DATABASE_URL));
test("E10: release and claim transfer the indexed balances", async () => {
  const f = await fixture(); await fund(f); await submitWork(f, "Completed work for release");
  const userBalanceData = encodeFunctionData({ abi, functionName: "balanceOf", args: [f.accounts[3] as Hex] });
  const walletBalance = async () => decodeFunctionResult({ abi, functionName: "balanceOf", data: await rpc<Hex>("eth_call", [{ to: f.token.address, data: userBalanceData }, "latest"]) });
  const before = await walletBalance();
  const feeWallet = f.accounts[6]!.toLowerCase();
  const feeUser = await f.prisma.user.upsert({ where: { walletAddress: feeWallet }, create: { walletAddress: feeWallet }, update: {} });
  const feeWhere = { chainId_contractAddress_address: { chainId: 31337, contractAddress: process.env.ESCROW_ADDRESS!.toLowerCase(), address: feeWallet } };
  const feePrior = (await f.prisma.claimableBalance.findUnique({ where: feeWhere }))?.amountRaw.toFixed() ?? "0";
  const balanceWhere = { chainId_contractAddress_address: { chainId: 31337, contractAddress: process.env.ESCROW_ADDRESS!.toLowerCase(), address: f.developer.walletAddress.toLowerCase() } };
  const prior = (await f.prisma.claimableBalance.findUnique({ where: balanceWhere }))?.amountRaw.toFixed() ?? "0";
  await releaseFunds(f);
  expect((await f.prisma.issue.findUniqueOrThrow({ where: { id: f.issueId } })).outcome).toBe("RELEASE");
  const credit = await f.prisma.claimableBalance.findUniqueOrThrow({ where: balanceWhere });
  expect(BigInt(credit.amountRaw.toFixed()) - BigInt(prior)).toBe(97500000n);
  expect(BigInt((await f.prisma.claimableBalance.findUniqueOrThrow({ where: feeWhere })).amountRaw.toFixed()) - BigInt(feePrior)).toBe(2500000n);
  const claimableData = encodeFunctionData({ abi: ESCROW_ABI, functionName: "claimable", args: [f.developer.walletAddress as Hex] });
  expect(decodeFunctionResult({ abi: ESCROW_ABI, functionName: "claimable", data: await rpc<Hex>("eth_call", [{ to: process.env.ESCROW_ADDRESS, data: claimableData }, "latest"]) })).toBe(BigInt(credit.amountRaw.toFixed()));
  expect(await f.prisma.notification.count({ where: { type: "ESCROW_RESOLVED", data: { path: ["issueId"], equals: f.issueId } } })).toBe(2);
  expect(await f.prisma.notification.count({ where: { type: "FUNDS_CLAIMABLE", userId: f.developer.id, data: { path: ["issueId"], equals: f.issueId } } })).toBe(1);
  expect(await f.prisma.notification.count({ where: { type: "FUNDS_CLAIMABLE", userId: feeUser.id, data: { path: ["issueId"], equals: f.issueId } } })).toBe(1);
  const claim = await gqlAs(f.developer, `mutation($recipient: String!) { prepareClaim(recipient: $recipient) { intentId method contractAddress data value } }`, { recipient: f.developer.walletAddress });
  expect(claim.errors).toBeUndefined();
  const step = claim.data?.prepareClaim as { intentId: string; method: string; contractAddress: Hex; data: Hex; value: string };
  await sendPrepared(f.developer, f.accounts[3]!, step);
  await waitFor(async () => (await f.prisma.transactionIntent.findUnique({ where: { id: step.intentId } }))?.status === "CONFIRMED");
  expect((await f.prisma.claimableBalance.findUniqueOrThrow({ where: balanceWhere })).amountRaw.toFixed()).toBe("0");
  expect(await walletBalance() - before).toBe(BigInt(credit.amountRaw.toFixed()));
  expect(await f.prisma.notification.count({ where: { userId: f.developer.id, type: "PAYMENT_RECEIVED" } })).toBeGreaterThan(0);
}, 120_000);
