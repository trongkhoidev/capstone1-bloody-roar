// Ghi ABI của BloodyRoarEscrow từ artifact Hardhat vào packages/shared/src/escrow/abi.ts.
// Chạy sau khi compile: `bun run apps/contracts/scripts/export-abi.ts` (từ thư mục gốc repo).
import { readFile, writeFile } from "node:fs/promises";

const artifactUrl = new URL("../artifacts/contracts/BloodyRoarEscrow.sol/BloodyRoarEscrow.json", import.meta.url);
const outputUrl = new URL("../../../packages/shared/src/escrow/abi.ts", import.meta.url);

const artifact = JSON.parse(await readFile(artifactUrl, "utf8")) as { abi: readonly unknown[] };
const body = `// Generated by apps/contracts/scripts/export-abi.ts. Không sửa tay.
export const ESCROW_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;

await writeFile(outputUrl, body, "utf8");
console.log(`Wrote ${artifact.abi.length} ABI items to packages/shared/src/escrow/abi.ts`);
