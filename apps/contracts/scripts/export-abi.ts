// Ghi ABI của BloodyRoarEscrow từ artifact Hardhat vào packages/shared/src/escrow/abi.ts.
// Chạy sau khi compile: `bun run apps/contracts/scripts/export-abi.ts` (từ thư mục gốc repo).
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

async function main() {
  const artifactPath = resolve(__dirname, "../artifacts/contracts/BloodyRoarEscrow.sol/BloodyRoarEscrow.json");
  const outputPath = resolve(__dirname, "../../../packages/shared/src/escrow/abi.ts");
  const artifact = JSON.parse(await readFile(artifactPath, "utf8")) as { abi: readonly unknown[] };
  const body = `// Generated by apps/contracts/scripts/export-abi.ts. Không sửa tay.
export const ESCROW_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;
  await writeFile(outputPath, body, "utf8");
  console.log(`Wrote ${artifact.abi.length} ABI items to packages/shared/src/escrow/abi.ts`);
}

main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
